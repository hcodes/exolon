// Re-extract the original effect streams from the TAP recovery memory image.
// This is an offline asset tool; no Z80 instructions execute in the browser.
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

export function extractOriginalAudio(memory) {
    if (memory.length !== 65536) throw new Error('Expected a complete 65536-byte memory image.');
    const ranges = [
        [0xc218, 0xc5e7],
        [0xc6eb, 0xc7ab],
    ];
    const sha256 = createHash('sha256').update(memory).digest('hex');
    const segments = ranges.map(([start, end]) => {
        const rows = [];
        for (let p = start; p < end; p += 16) {
            rows.push(
                `        ${Array.from(memory.subarray(p, Math.min(p + 16, end)), (n) => `0x${n.toString(16).padStart(2, '0')}`).join(', ')},`,
            );
        }
        return `    [0x${start.toString(16)}, Uint8Array.from([\n${rows.join('\n')}\n    ])],`;
    });
    return `// Generated by tools/audio/zx.mjs from the original Exolon TAP.\n// Memory SHA-256: ${sha256}\n// Original game: Raffaele Cecco / Nick Jones, Hewson, 1987.\n// Effect labels and decoding follow Sergey Erokhin's CC-BY-SA 3.0 disassembly:\n// https://bitbucket.org/esl/exolon-zx/ (asm/sound_psg.asm)\nconst segments = [\n${segments.join('\n')}\n];\n\nexport function originalByte(address) {\n    for (const [start, data] of segments) {\n        if (address >= start && address < start + data.length) return data[address - start];\n    }\n    throw new RangeError(\x60Address outside original audio data: \x24{address.toString(16)}\x60);\n}\n`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
    const input = process.argv[2];
    if (!input) throw new Error('Pass the recovered 65536-byte Exolon memory.bin.');
    const memory = await readFile(input);
    const output = new URL('../../src/audio/original-data.js', import.meta.url);
    await mkdir(new URL('.', output), { recursive: true });
    await writeFile(output, extractOriginalAudio(memory));
    console.log(`Recovered original effects into ${fileURLToPath(output)}.`);
}
