import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { rolldown } from 'rolldown';
import { runtimeConfig } from '../../rolldown.config.mjs';
import { legacyArtifacts } from './legacy-artifacts.mjs';

const development = process.argv.includes('--dev');
const { files, chunks } = await legacyArtifacts({ development });
const dir = fileURLToPath(new URL('../../dist/legacy/', import.meta.url));
await fs.mkdir(dir, { recursive: true });
for (const [name, code] of files) await fs.writeFile(path.join(dir, name), code);
await fs.writeFile(path.join(dir, 'chunks.json'), JSON.stringify(chunks, null, 4) + '\n');
// Extract from the same complete dependency graph as modern. The legacy shell deliberately
// cannot import engine modules, so extracting its graph alone would omit their styles.
const { output: options, ...input } = runtimeConfig({ development });
const bundle = await rolldown(input);
try {
    const { output } = await bundle.generate(options);
    const stylesheet = output.find(
        (item) => item.type === 'asset' && item.fileName === 'index.css',
    );
    if (!stylesheet) throw new Error('Legacy component CSS is missing');
    await fs.writeFile(
        path.join(dir, 'index.css'),
        '/* Generated by npm run build:legacy. Do not edit. */\n' +
            String(stylesheet.source).replace(/#([\da-f]{8}|[\da-f]{4})\b/gi, (_, value) => {
                const hex =
                    value.length === 4
                        ? value
                              .split('')
                              .map((n) => n + n)
                              .join('')
                        : value;
                return `rgba(${parseInt(hex.slice(0, 2), 16)},${parseInt(hex.slice(2, 4), 16)},${parseInt(hex.slice(4, 6), 16)},${parseInt(hex.slice(6, 8), 16) / 255})`;
            }),
    );
} finally {
    await bundle.close();
}
console.log(
    `Legacy ES5 shell and three deferred engines built (${development ? 'development' : 'production'}).`,
);
