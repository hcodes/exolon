import { mkdir } from 'node:fs/promises';
import { rolldown } from 'rolldown';
import { fileURLToPath } from 'node:url';

const output = new URL('../../.cache/build/', import.meta.url);
await mkdir(output, { recursive: true });
const bundle = await rolldown({
    input: fileURLToPath(new URL('../../src/entries/preferences.ts', import.meta.url)),
});
try {
    await bundle.write({
        file: fileURLToPath(new URL('preferences.mjs', output)),
        format: 'es',
        banner: '// Generated by npm run build:preferences from src/entries/preferences.ts. Do not edit.',
    });
} finally {
    await bundle.close();
}
